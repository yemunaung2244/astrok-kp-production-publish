function offlineYatraReading(questionText) {
  if (typeof deck === 'undefined') return '';
  const { intent, cleanSubject } = classifyQuestion(questionText);
  let key = 'general';
  if (intent) {
    if (intent.id.startsWith('love_') || intent.id === 'family_harmony') key = 'love';
    else if (intent.id.startsWith('work_')) key = 'work';
    else if (intent.id.startsWith('money_') || intent.id === 'lost_item') key = 'money';
    else if (intent.id.startsWith('health_')) key = 'health';
    else if (intent.id.startsWith('edu_')) key = 'edu';
    else if (intent.id.startsWith('travel_')) key = 'travel';
    else if (intent.id === 'legal_case') key = 'legal';
    else if (intent.id === 'appointment_arrival') key = 'appointment';
  }
  const profile = yatraProfiles[key] || yatraProfiles.general;
  const cardId = profile.cardId;
  const cardName = deck[cardId][1];
  const cardTheme = deck[cardId][2];
  const topicText = cleanSubject && cleanSubject.length <= 60 ? `“${cleanSubject}”` : 'လက်ရှိပြဿနာ';
  return `[[CARD:${cardId}]]\n\n**အဆောင်တားရော့ကတ် — ${cardName} (${cardTheme})**\nဇာတာရှင်ရဲ့ ${topicText} အတွက် အသင့်တော်ဆုံး အဆောင်တားရော့ကတ်မှာ **${cardName}** ဖြစ်ပါတယ်ခင်ဗျာ။ ${profile.talisman}\n\n**ဆောင်ရွက်ရမည့် ယတြာ**\n${profile.remedy}`;
}
