const patternIndex = [];
for (const [intentId, subjects, actions, endings] of patternGroups) {
  for (const s of subjects) {
    for (const a of actions) {
      for (const e of endings) {
        patternIndex.push({ intentId, phrase: (s + a + e).toLowerCase(), core: (a + e).toLowerCase(), action: a.toLowerCase() });
      }
    }
  }
}

const intentMap = new Map(subIntents.map(item => [item.id, item]));

function classifyQuestion(questionText) {
  const raw = (questionText || '').trim();
  const q = raw.toLowerCase();
  const compact = q.replace(/\s+/g, '');
  let bestIntent = null;
  let bestScore = 0;

  for (const intent of subIntents) {
    let score = 0;
    for (const [term, weight] of intent.keywords) {
      if (q.includes(term.toLowerCase())) score += weight;
    }
    if (score > bestScore) {
      bestScore = score;
      bestIntent = intent;
    }
  }

  for (const entry of patternIndex) {
    let pScore = 0;
    if (compact.includes(entry.phrase)) pScore = 12;
    else if (compact.includes(entry.core)) pScore = 7;
    else if (compact.includes(entry.action)) pScore = 4;
    if (pScore > bestScore) {
      const matched = intentMap.get(entry.intentId);
      if (matched) {
        bestScore = pScore;
        bestIntent = matched;
      }
    }
  }

  const cleanSubject = raw
    .replace(/[?？။!\s]+$/g, '')
    .replace(/(နိုင်မလား|ဖြစ်မလား|အဆင်ပြေမလား|ကောင်းမလား|သင့်လား|ရမလား|မလား|လား)$/g, '')
    .trim();
  return { intent: bestIntent, cleanSubject };
}

function offlineQuestionReading(cardId, questionText) {
  if (typeof deck === 'undefined' || !deck[cardId]) return '';
  const cardName = deck[cardId][1];
  const cardTheme = deck[cardId][2];
  const polarity = cardPolarity[cardId] || 'wait';
  const { intent, cleanSubject } = classifyQuestion(questionText);

  if (intent) {
    const direct = intent.answers[polarity];
    const advice = intent.advice[polarity];
    return `ဒီ **${cardName}** ကတ်အရ မေးထားတဲ့ကိစ္စမှာ **${direct}**ခင်ဗျာ။ ကတ်ရဲ့ **${cardTheme}** သဘောတရားက ဒီအခြေအနေကို ညွှန်ပြနေပါတယ်။ ${advice}`;
  }

  const subjectLabel = cleanSubject && cleanSubject.length <= 60 ? `“${cleanSubject}”` : 'မေးထားတဲ့ ကိစ္စ';
  if (polarity === 'yes') {
    return `ဒီ **${cardName}** ကတ်အရ ${subjectLabel} မှာ **အဆင်ပြေ အောင်မြင်နိုင်ခြေ များပါတယ်**ခင်ဗျာ။ ကတ်ရဲ့ **${cardTheme}** စွမ်းအင်ကြောင့် ယုံကြည်ချက်ရှိရှိ လက်တွေ့စတင်လုပ်ဆောင်သင့်ပါတယ်။`;
  }
  if (polarity === 'wait') {
    return `ဒီ **${cardName}** ကတ်အရ ${subjectLabel} မှာ **အလျင်စလို မဆုံးဖြတ်ဘဲ အချိန်ယူစဉ်းစားသင့်တဲ့ အခြေအနေ** ဖြစ်ပါတယ်ခင်ဗျာ။ ကတ်ရဲ့ **${cardTheme}** သဘောအတိုင်း အချက်အလက်တွေ သေချာစစ်ဆေးပြီးမှ ရှေ့တိုးပါ။`;
  }
  return `ဒီ **${cardName}** ကတ်အရ ${subjectLabel} မှာ **သတိထားစောင့်ကြည့်သင့်ပြီး လောလောဆယ် မလုပ်သေးတာ ပိုကောင်းပါတယ်**ခင်ဗျာ။ ကတ်ရဲ့ **${cardTheme}** အချက်ပြမှုအရ မလိုအပ်တဲ့ စွန့်စားမှုကို ခဏရှောင်ပြီး အရင်ပြင်ဆင်ထားပါ။`;
}

